alter table public.automations enable row level security;
alter table public.automation_sends enable row level security;

create policy "Business read" on public.automations for select to authenticated using (business_id = (select public.current_business_id()));
create policy "Booking managers insert" on public.automations for insert to authenticated with check (business_id = (select public.current_business_id()) and (select public.can_manage_booking()));
create policy "Booking managers update" on public.automations for update to authenticated using (business_id = (select public.current_business_id()) and (select public.can_manage_booking())) with check (business_id = (select public.current_business_id()));

-- Written by the server only
create policy "Business read" on public.automation_sends for select to authenticated using (business_id = (select public.current_business_id()));
