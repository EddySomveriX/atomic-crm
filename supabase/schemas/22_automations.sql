--
-- Automatic messages to clients in Telegram (second batch of improvements):
-- five ready scenarios a business turns on with a switch.
--   rebook        N days after a service (N set per service), when the client
--                 has nothing booked: "time to repeat"
--   no_show       after a missed visit: "book another time"
--   review        2 hours after a completed visit: thanks and a review link
--   birthday      on the client's birthday
--   reactivation  N days (60 by default) after the last visit
-- Each message is claimed once in automation_sends before it is sent, so it
-- never goes out twice; messages go out from 9:00 to 20:00 business time,
-- only to clients who agreed to the bot's terms and did not write "stop".
--

alter table public.products
    add column rebook_days smallint;
alter table public.products
    add constraint products_rebook_days check (rebook_days between 1 and 365);

alter table public.companies
    add column birth_date date;

-- Counterparties with the client fields of the card: reliability choice,
-- personal discount and birthday (earlier columns: 13_counterparties.sql)
create or replace view public.companies_summary with (security_invoker = on) as
select
    c.id,
    c.created_at,
    c.name,
    c.sector,
    c.size,
    c.linkedin_url,
    c.website,
    c.phone_number,
    c.address,
    c.zipcode,
    c.city,
    c.state_abbr,
    c.sales_id,
    c.context_links,
    c.country,
    c.description,
    c.revenue,
    c.tax_identifier,
    c.logo,
    c.kind,
    c.roles,
    c.country_code,
    c.requisites,
    c.vat_id,
    c.vat_status,
    c.vat_checked_at,
    c.currency,
    c.payment_terms_days,
    c.credit_limit,
    count(distinct d.id) as nb_deals,
    count(distinct co.id) as nb_contacts,
    c.reliability_override,
    c.personal_discount,
    c.birth_date
from public.companies c
    left join public.deals d on c.id = d.company_id
    left join public.contacts co on c.id = co.company_id
group by c.id;

-- Products with the days after which a service is repeated (earlier
-- columns: 14_products_stock.sql, 15_booking.sql, 20_pricing.sql)
create or replace view public.products_summary with (security_invoker = on) as
select
    p.id,
    p.business_id,
    p.created_at,
    p.kind,
    p.name,
    p.sku,
    p.unit_code,
    p.price,
    p.currency,
    p.vat_rate_code,
    p.barcodes,
    p.description,
    p.archived,
    coalesce((
        select sum(case when m.to_warehouse_id is not null and m.from_warehouse_id is null then m.quantity
                        when m.from_warehouse_id is not null and m.to_warehouse_id is null then -m.quantity
                        else 0 end)
        from public.stock_moves m
        where m.product_id = p.id
    ), 0) as quantity,
    (
        select round(sum(m.quantity * m.unit_cost) / nullif(sum(m.quantity), 0))::bigint
        from public.stock_moves m
        where m.product_id = p.id
          and m.kind = 'receipt'
          and not exists (select 1 from public.stock_moves r where r.reverses_id = m.id)
    ) as average_cost,
    p.duration_minutes,
    p.buffer_minutes,
    p.category,
    p.show_online,
    p.sort_order,
    p.is_addon,
    p.rebook_days
from public.products p;

-- When the client wrote "stop": no automatic messages from then on
alter table public.conversations
    add column automations_off_at timestamp with time zone;

create table public.automations (
    id bigint generated by default as identity primary key,
    business_id uuid not null default public.current_business_id(),
    created_at timestamp with time zone not null default now(),
    kind text not null,
    enabled boolean not null default false,
    -- reactivation: days without a visit
    days smallint,
    -- review: where to leave a review (Google Maps, Instagram...)
    link text,
    -- The business's own text instead of the standard one
    custom_text text,
    constraint automations_kind check (kind in ('rebook', 'no_show', 'review', 'birthday', 'reactivation')),
    constraint automations_days check (days between 14 and 365),
    constraint automations_link check (link ~ '^https://[^\s]{4,500}$'),
    constraint automations_custom_text check (length(btrim(custom_text)) between 1 and 1000),
    constraint automations_business_id_kind_key unique (business_id, kind)
);

alter table public.automations
    add constraint automations_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;

create table public.automation_sends (
    id bigint generated by default as identity primary key,
    business_id uuid not null,
    created_at timestamp with time zone not null default now(),
    kind text not null,
    -- What the message is about, so that it goes out once: the booking, or
    -- the client and the year of the birthday
    dedupe_key text not null,
    client_id bigint,
    booking_id bigint,
    conversation_id bigint,
    status text not null default 'pending',
    error text,
    sent_at timestamp with time zone,
    constraint automation_sends_kind check (kind in ('rebook', 'no_show', 'review', 'birthday', 'reactivation')),
    constraint automation_sends_status check (status in ('pending', 'sent', 'failed')),
    constraint automation_sends_once unique (business_id, kind, dedupe_key)
);

alter table public.automation_sends
    add constraint automation_sends_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;
alter table public.automation_sends
    add constraint automation_sends_client_id_fkey foreign key (client_id, business_id) references public.companies(id, business_id) on delete set null (client_id);
alter table public.automation_sends
    add constraint automation_sends_booking_id_fkey foreign key (booking_id, business_id) references public.bookings(id, business_id) on delete set null (booking_id);
alter table public.automation_sends
    add constraint automation_sends_conversation_id_fkey foreign key (conversation_id, business_id) references public.conversations(id, business_id) on delete set null (conversation_id);

create index automation_sends_business_id_created_at_idx on public.automation_sends using btree (business_id, created_at desc);
create index automation_sends_client_id_idx on public.automation_sends using btree (client_id);
create index automation_sends_booking_id_idx on public.automation_sends using btree (booking_id);
create index automation_sends_conversation_id_idx on public.automation_sends using btree (conversation_id);

--
-- Messages that are due, claimed once. Server only.
--

CREATE OR REPLACE FUNCTION "public"."claim_due_automations"("p_now" timestamp with time zone DEFAULT now()) RETURNS TABLE("send_id" bigint, "kind" "text", "client_id" bigint, "booking_id" bigint, "conversation_id" bigint)
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  return query
  with active as (
      -- Businesses with the automation on, inside their sending hours
      select a.business_id, a.kind, coalesce(a.days, 60) as days, bz.timezone
      from public.automations a
      join public.businesses bz on bz.id = a.business_id
      where a.enabled
        and extract(hour from p_now at time zone bz.timezone) between 9 and 19
  ),
  due as (
      select ac.business_id, ac.kind, b.id::text as dedupe_key, b.client_id, b.id as booking_id
      from active ac
      join public.bookings b on b.business_id = ac.business_id
      where ac.kind = 'review' and b.status = 'completed' and b.client_id is not null
        and b.ends_at <= p_now - interval '2 hours'
        and b.ends_at > p_now - interval '26 hours'
      union all
      select ac.business_id, ac.kind, b.id::text, b.client_id, b.id
      from active ac
      join public.bookings b on b.business_id = ac.business_id
      where ac.kind = 'no_show' and b.status = 'no_show' and b.client_id is not null
        and b.starts_at <= p_now
        and b.starts_at > p_now - interval '48 hours'
      union all
      select ac.business_id, ac.kind, b.id::text, b.client_id, b.id
      from active ac
      join public.bookings b on b.business_id = ac.business_id
      join public.products p on p.id = b.product_id
      where ac.kind = 'rebook' and b.status = 'completed' and b.client_id is not null
        and p.rebook_days is not null
        and b.ends_at <= p_now - make_interval(days => p.rebook_days)
        and b.ends_at > p_now - make_interval(days => p.rebook_days + 7)
        -- the latest visit for this service, and nothing booked ahead
        and not exists (
            select 1 from public.bookings later
            where later.client_id = b.client_id and later.business_id = b.business_id
              and later.product_id = b.product_id and later.status = 'completed'
              and later.starts_at > b.starts_at)
        and not exists (
            select 1 from public.bookings ahead
            where ahead.client_id = b.client_id and ahead.business_id = b.business_id
              and ahead.status = 'booked' and ahead.starts_at > p_now)
      union all
      select ac.business_id, ac.kind,
             c.id || ':' || extract(year from p_now at time zone ac.timezone),
             c.id, null::bigint
      from active ac
      join public.companies c on c.business_id = ac.business_id
      where ac.kind = 'birthday' and c.birth_date is not null
        and to_char(c.birth_date, 'MM-DD') = to_char(p_now at time zone ac.timezone, 'MM-DD')
      union all
      select ac.business_id, ac.kind, last_visit.id::text, last_visit.client_id, last_visit.id
      from active ac
      join lateral (
          select distinct on (b.client_id) b.id, b.client_id, b.ends_at
          from public.bookings b
          where b.business_id = ac.business_id and b.client_id is not null
            and b.status in ('completed', 'booked')
          order by b.client_id, b.starts_at desc
      ) last_visit on true
      join public.bookings lb on lb.id = last_visit.id
      where ac.kind = 'reactivation' and lb.status = 'completed'
        and last_visit.ends_at <= p_now - make_interval(days => ac.days)
        and last_visit.ends_at > p_now - make_interval(days => ac.days + 14)
  ),
  reachable as (
      select d.*, (
          select cv.id
          from public.conversations cv
          join public.channels ch on ch.id = cv.channel_id
          where cv.client_id = d.client_id and cv.business_id = d.business_id
            and ch.enabled and public.chat_reachable(ch.kind, cv.last_inbound_at, p_now)
            and cv.consent_at is not null and cv.automations_off_at is null
          order by cv.last_message_at desc nulls last
          limit 1
      ) as conversation_id
      from due d
  ),
  claimed as (
      insert into public.automation_sends (business_id, kind, dedupe_key, client_id, booking_id, conversation_id)
      select r.business_id, r.kind, r.dedupe_key, r.client_id, r.booking_id, r.conversation_id
      from reachable r
      where r.conversation_id is not null
      on conflict on constraint automation_sends_once do nothing
      returning automation_sends.id, automation_sends.kind, automation_sends.client_id,
                automation_sends.booking_id, automation_sends.conversation_id
  )
  select * from claimed;
end;
$$;

revoke all on function public.claim_due_automations(timestamp with time zone) from public, anon, authenticated;
grant execute on function public.claim_due_automations(timestamp with time zone) to service_role;

