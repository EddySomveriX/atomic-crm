alter table public.documents enable row level security;

create policy "Business read" on public.documents for select to authenticated using (business_id = (select public.current_business_id()));
create policy "Business insert" on public.documents for insert to authenticated with check (business_id = (select public.current_business_id()) and (select public.can_write_current_business()));
create policy "Business update" on public.documents for update to authenticated using (business_id = (select public.current_business_id()) and (select public.can_write_current_business())) with check (business_id = (select public.current_business_id()));

-- The private bucket: members reach the files of their own business only
create policy "Documents read" on storage.objects for select to authenticated using (bucket_id = 'documents' and (select public.is_own_document_path(name)));
create policy "Documents upload" on storage.objects for insert to authenticated with check (bucket_id = 'documents' and (select public.is_own_document_path(name)) and (select public.can_write_current_business()));

