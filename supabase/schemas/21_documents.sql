--
-- Documents (TZ section 6.4, first part): scans, photos and files of a
-- business, kept in a private storage bucket where each business has its own
-- folder (<business id>/...). A document belongs to a counterparty, a
-- contact, a deal or a booking, has a kind, a date and an amount, and a
-- checksum so that the same file is not stored twice. Only an owner moves a
-- document to the trash; the server removes it for good after 30 days.
-- Recognition of the fields by AI comes later (stage 5).
--

alter table public.businesses drop constraint businesses_modules;
alter table public.businesses
    add constraint businesses_modules check (modules <@ array['chats', 'booking', 'sales', 'stock', 'tasks', 'analytics', 'pricing', 'documents']);

CREATE OR REPLACE FUNCTION "public"."default_modules"("p_business_type" "text") RETURNS "text"[]
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
    select case p_business_type
        when 'services' then array['chats', 'booking', 'pricing', 'tasks', 'analytics']
        when 'retail' then array['chats', 'sales', 'stock', 'pricing', 'documents', 'analytics']
        when 'production' then array['sales', 'stock', 'documents', 'tasks', 'analytics']
        when 'b2b' then array['chats', 'sales', 'documents', 'tasks', 'analytics']
        else array['chats', 'booking', 'sales', 'stock', 'tasks', 'analytics', 'pricing', 'documents']
    end
$$;

create table public.documents (
    id bigint generated by default as identity primary key,
    business_id uuid not null default public.current_business_id(),
    created_at timestamp with time zone not null default now(),
    created_by uuid default auth.uid(),
    kind text not null default 'other',
    title text not null,
    doc_date date,
    -- Amount in minor units of the business currency
    amount bigint,
    -- Path in the documents bucket: <business id>/<random>/<file name>
    file_path text not null,
    file_name text not null,
    mime_type text not null,
    size_bytes bigint not null,
    -- SHA-256 of the file, hex: the same file is not stored twice
    checksum text not null,
    source text not null default 'upload',
    company_id bigint,
    contact_id bigint,
    deal_id bigint,
    booking_id bigint,
    deleted_at timestamp with time zone,
    deleted_by uuid,
    constraint documents_kind check (kind in ('contract', 'invoice', 'act', 'waybill', 'receipt', 'photo', 'other')),
    constraint documents_title_length check (length(btrim(title)) between 1 and 200),
    constraint documents_amount check (amount >= 0),
    constraint documents_size check (size_bytes between 1 and 20971520),
    constraint documents_checksum_format check (checksum ~ '^[0-9a-f]{64}$'),
    constraint documents_source check (source in ('upload', 'telegram', 'chat')),
    constraint documents_file_path_key unique (file_path)
);

alter table public.documents
    add constraint documents_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;
alter table public.documents
    add constraint documents_company_id_fkey foreign key (company_id, business_id) references public.companies(id, business_id) on delete set null (company_id);
alter table public.documents
