create index documents_contact_id_idx on public.documents using btree (contact_id);
create index documents_deal_id_idx on public.documents using btree (deal_id);
create index documents_booking_id_idx on public.documents using btree (booking_id);

--
-- Rules
--

-- A file of the documents bucket belongs to the business of its first folder
CREATE OR REPLACE FUNCTION "public"."is_own_document_path"("p_name" "text") RETURNS boolean
    LANGUAGE "sql" STABLE
    SET "search_path" TO ''
    AS $$ select (storage.foldername(p_name))[1] = public.current_business_id()::text $$;

-- The file stays in the business folder; only an owner moves a document to
-- the trash or back
CREATE OR REPLACE FUNCTION "public"."check_document"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if split_part(new.file_path, '/', 1) <> new.business_id::text then
    raise exception 'A document file is kept in the folder of its business' using errcode = '42501';
  end if;
  if tg_op = 'UPDATE' then
    if new.file_path <> old.file_path or new.checksum <> old.checksum then
      raise exception 'The file of a document does not change' using errcode = '42501';
    end if;
    if new.deleted_at is distinct from old.deleted_at then
      if auth.uid() is not null and not public.is_admin() then
        raise exception 'Only an owner moves documents to the trash' using errcode = '42501';
      end if;
      new.deleted_by := case when new.deleted_at is null then null else auth.uid() end;
    end if;
  end if;
  return new;
end;
$$;

create or replace trigger check_document
    before insert or update on public.documents
    for each row execute function public.check_document();

