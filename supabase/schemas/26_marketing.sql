    constraint marketing_accounts_name_length check (length(btrim(name)) between 1 and 200),
    constraint marketing_accounts_business_id_kind_external_id_key unique (business_id, kind, external_id),
    constraint marketing_accounts_id_business_id_key unique (id, business_id)
);

