--
-- Marketing: posts planned in the CRM and published at their time to the
-- business's Telegram channel and Instagram business account.
-- An account is connected by the server (it checks the channel or the token);
-- the Instagram token lives in marketing_secrets, which only the server reads.
-- A post has a text, photos or a video, a format (post, story, reel) and the
-- accounts it goes to; each account is a target published once: the server
-- claims due targets (claim_due_posts) so a repeated run never posts twice.
-- Media live in the private post_media bucket, one folder per business.
-- A client card keeps the client's Instagram username.
--

alter table public.businesses drop constraint businesses_modules;
alter table public.businesses
    add constraint businesses_modules check (modules <@ array['chats', 'booking', 'sales', 'stock', 'tasks', 'analytics', 'pricing', 'documents', 'marketing']);

CREATE OR REPLACE FUNCTION "public"."default_modules"("p_business_type" "text") RETURNS "text"[]
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
    select case p_business_type
        when 'services' then array['chats', 'booking', 'pricing', 'marketing', 'tasks', 'analytics']
        when 'retail' then array['chats', 'sales', 'stock', 'pricing', 'marketing', 'documents', 'analytics']
        when 'production' then array['sales', 'stock', 'documents', 'tasks', 'analytics']
        when 'b2b' then array['chats', 'sales', 'documents', 'tasks', 'analytics']
        else array['chats', 'booking', 'sales', 'stock', 'tasks', 'analytics', 'pricing', 'documents', 'marketing']
    end
$$;

