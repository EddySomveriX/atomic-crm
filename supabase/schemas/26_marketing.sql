-- Owners and managers run the marketing
CREATE OR REPLACE FUNCTION "public"."can_manage_marketing"() RETURNS boolean
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$ select coalesce(public.current_business_role() in ('owner', 'manager'), false) $$;

-- A file of the post_media bucket belongs to the business of its first folder
CREATE OR REPLACE FUNCTION "public"."is_own_post_media_path"("p_name" "text") RETURNS boolean
    LANGUAGE "sql" STABLE
    SET "search_path" TO ''
    AS $$ select (storage.foldername(p_name))[1] = public.current_business_id()::text $$;

-- A published post (or one being published) keeps its content and targets
CREATE OR REPLACE FUNCTION "public"."protect_post"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  if exists (select 1 from public.post_targets t
             where t.post_id = old.id and t.status in ('publishing', 'published')) then
    if tg_op = 'DELETE' then
      if not exists (select 1 from public.businesses b where b.id = old.business_id) then
        return old;
      end if;
      raise exception 'A published post is kept' using errcode = '42501';
    end if;
    if new.text is distinct from old.text or new.media is distinct from old.media
       or new.format is distinct from old.format or new.scheduled_at is distinct from old.scheduled_at then
      raise exception 'A published post cannot be changed' using errcode = '42501';
    end if;
  end if;
  return coalesce(new, old);
end;
$$;

-- A target goes to an account of the post's format: a story or a reel only
-- to Instagram
CREATE OR REPLACE FUNCTION "public"."check_post_target"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  post_format text;
  account_kind text;
begin
  select p.format into post_format from public.posts p where p.id = new.post_id and p.business_id = new.business_id;
  select a.kind into account_kind from public.marketing_accounts a where a.id = new.account_id and a.business_id = new.business_id;
  if post_format in ('story', 'reel') and account_kind <> 'instagram' then
    raise exception 'Stories and reels go to Instagram only' using errcode = '23514';
  end if;
  return new;
end;
$$;

-- The status of a post follows its targets
CREATE OR REPLACE FUNCTION "public"."refresh_post_status"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  done integer;
  failed integer;
  total integer;
begin
  select count(*) filter (where t.status = 'published'), count(*) filter (where t.status = 'failed'), count(*)
  into done, failed, total
  from public.post_targets t where t.post_id = new.post_id;
  if done + failed < total then
    return new;
  end if;
  update public.posts p
  set status = case when failed = 0 then 'published' when done = 0 then 'failed' else 'partly' end
  where p.id = new.post_id;
  return new;
end;
$$;

-- Claims the targets of the scheduled posts that are due, each once, and
-- returns what the server needs to publish them. Service role only.
CREATE OR REPLACE FUNCTION "public"."claim_due_posts"("p_now" timestamp with time zone DEFAULT "now"()) RETURNS TABLE("target_id" bigint, "post_id" bigint, "business_id" "uuid", "account_id" bigint, "account_kind" "text", "external_id" "text", "format" "text", "text" "text", "media" "jsonb")
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  -- A target stuck while publishing for 15 minutes failed
  update public.post_targets t
  set status = 'failed', error = 'publishing did not finish'
  where t.status = 'publishing' and t.claimed_at < p_now - interval '15 minutes';

  return query
  with due as (
      select t.id
      from public.post_targets t
      join public.posts p on p.id = t.post_id
      join public.marketing_accounts a on a.id = t.account_id
      where t.status = 'pending' and p.status = 'scheduled' and p.scheduled_at <= p_now and a.enabled
      order by p.scheduled_at, t.id
      limit 20
      for update of t skip locked
  ), claimed as (
      update public.post_targets t
      set status = 'publishing', claimed_at = p_now
      from due
      where t.id = due.id
      returning t.id, t.post_id, t.business_id, t.account_id
  )
  select c.id, c.post_id, c.business_id, c.account_id, a.kind, a.external_id, p.format, p.text, p.media
  from claimed c
  join public.posts p on p.id = c.post_id
  join public.marketing_accounts a on a.id = c.account_id
  order by c.id;
end;
$$;

-- Publishes again the targets of a post that failed, now
CREATE OR REPLACE FUNCTION "public"."retry_post"("p_post_id" bigint) RETURNS void
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if not public.can_manage_marketing() or not exists (
      select 1 from public.posts p where p.id = p_post_id and p.business_id = public.current_business_id()) then
    raise exception 'Not a post of this business' using errcode = '42501';
  end if;
  update public.post_targets t
  set status = 'pending', error = null, claimed_at = null
  where t.post_id = p_post_id and t.status = 'failed';
  if not found then
    raise exception 'Nothing to publish again' using errcode = '22023';
  end if;
  -- Its time has passed, so the next run publishes it
  update public.posts p set status = 'scheduled' where p.id = p_post_id;
end;
$$;

create or replace trigger protect_post
    before update or delete on public.posts
    for each row execute function public.protect_post();

create or replace trigger check_post_target
    before insert or update of account_id, post_id on public.post_targets
    for each row execute function public.check_post_target();

create or replace trigger refresh_post_status
    after update of status on public.post_targets
    for each row when (new.status in ('published', 'failed'))
    execute function public.refresh_post_status();

