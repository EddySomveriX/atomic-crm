create table public.posts (
    id bigint generated by default as identity primary key,
    business_id uuid not null default public.current_business_id(),
    created_at timestamp with time zone not null default now(),
    created_by uuid default auth.uid(),
    format text not null default 'post',
    text text not null default '',
    -- [{"path": "<business id>/<random>/<file>", "mime": "image/jpeg"}]
    media jsonb not null default '[]'::jsonb,
    -- Empty: a draft
    scheduled_at timestamp with time zone,
    status text not null default 'draft',
    -- Where the draft came from: an offer, the free slots of a day, or by hand
    source text not null default 'manual',
    promotion_id bigint,
    constraint posts_format check (format in ('post', 'story', 'reel')),
    -- 2 200 characters: the longest Instagram caption
    constraint posts_text_length check (length(text) <= 2200),
    constraint posts_media_list check (jsonb_typeof(media) = 'array' and jsonb_array_length(media) <= 10),
    constraint posts_status check (status in ('draft', 'scheduled', 'published', 'partly', 'failed')),
    constraint posts_source check (source in ('manual', 'offer', 'free_slots')),
    constraint posts_scheduled check (status = 'draft' or scheduled_at is not null),
    constraint posts_id_business_id_key unique (id, business_id)
);

create table public.post_targets (
    id bigint generated by default as identity primary key,
    business_id uuid not null default public.current_business_id(),
    post_id bigint not null,
    account_id bigint not null,
    status text not null default 'pending',
    -- Id and link of the published post in the channel
    external_id text,
    url text,
    error text,
    claimed_at timestamp with time zone,
    published_at timestamp with time zone,
    constraint post_targets_status check (status in ('pending', 'publishing', 'published', 'failed')),
    constraint post_targets_error_length check (error is null or length(error) <= 500),
    constraint post_targets_post_id_account_id_key unique (post_id, account_id)
);

