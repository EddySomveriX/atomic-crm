--
-- Cost of services and goods
-- How a business counts the full cost of what it sells: the materials, the
-- pay of the specialist, a share of the monthly expenses by the minutes a
-- service takes (time-driven activity-based costing), taxes and bank fees,
-- and lines of its own per service or goods. The interface does the sums;
-- the database keeps the inputs and gathers the figures it needs.
-- Owners, managers and accountants see costs; owners and managers change them.
-- Income tax rates offered as a hint come from the country pack (tax_rates,
-- tax = 'income'); their rows live in the migration.
--

create table public.cost_settings (
    business_id uuid not null default public.current_business_id() primary key,
    updated_at timestamp with time zone not null default now(),
    -- Share of the working time that is actually booked, used to spread expenses
    load_percent smallint not null default 75,
    -- How the specialist is paid: a percent of the price or by the hour
    pay_mode text not null default 'commission',
    -- Pay per hour in minor units (pay_mode = 'hourly')
    hourly_rate bigint,
    tax_percent numeric(5,2) not null default 0,
    card_fee_percent numeric(5,2) not null default 0,
    -- Share of payments made by card
    card_share_percent smallint not null default 0,
    -- How a price is formed from the cost, for services and for goods:
    -- margin (percent of the price), markup (percent of the cost) or profit
    -- (minor units on every sale); see 30_price_rules.sql
    service_price_method text not null default 'margin',
    service_price_value numeric(12,2) not null default 30,
    goods_price_method text not null default 'markup',
    goods_price_value numeric(12,2) not null default 50,
    -- Rounding of a calculated price: up to 1, 10, 50 or 100 currency
    -- units, or up to a price ending in 9 or 99
    price_rounding text not null default 'none',
    -- Materials and goods at the average purchase cost or the last one
    material_price text not null default 'average',
    constraint cost_settings_load check (load_percent between 1 and 100),
    constraint cost_settings_pay_mode check (pay_mode in ('commission', 'hourly')),
    constraint cost_settings_hourly_rate check (hourly_rate >= 0),
    constraint cost_settings_tax check (tax_percent between 0 and 99),
    constraint cost_settings_card_fee check (card_fee_percent between 0 and 99),
    constraint cost_settings_card_share check (card_share_percent between 0 and 100),
    constraint cost_settings_service_price check (
        (service_price_method = 'margin' and service_price_value between 0 and 95)
        or (service_price_method = 'markup' and service_price_value between 0 and 1000)
        or (service_price_method = 'profit' and service_price_value >= 0)
    ),
    constraint cost_settings_goods_price check (
        (goods_price_method = 'margin' and goods_price_value between 0 and 95)
        or (goods_price_method = 'markup' and goods_price_value between 0 and 1000)
        or (goods_price_method = 'profit' and goods_price_value >= 0)
    ),
    constraint cost_settings_price_rounding check (price_rounding in ('none', '1', '10', '50', '100', '9', '99')),
    constraint cost_settings_material_price check (material_price in ('average', 'last'))
);

-- Monthly expenses: an amount a month, or equipment bought for a price and
-- used for a number of months (its price is spread over those months)
create table public.overhead_items (
    id bigint generated by default as identity primary key,
    business_id uuid not null default public.current_business_id(),
    created_at timestamp with time zone not null default now(),
    name text not null,
    kind text not null default 'monthly',
    -- Minor units: the amount a month, or the price of the equipment
    amount bigint not null,
    -- Months of use of the equipment
    months smallint,
    constraint overhead_items_name_length check (length(btrim(name)) between 1 and 200),
    constraint overhead_items_kind check (kind in ('monthly', 'equipment')),
    constraint overhead_items_amount check (amount >= 0),
    constraint overhead_items_months check (
        case kind when 'equipment' then coalesce(months between 1 and 600, false) else months is null end
    )
);

-- Lines of its own in the cost of one service or one unit of goods: an
-- amount (disposable tools, delivery, packaging) or a percent of the price
create table public.product_cost_items (
    id bigint generated by default as identity primary key,
    business_id uuid not null default public.current_business_id(),
    created_at timestamp with time zone not null default now(),
    product_id bigint not null,
    name text not null,
    amount bigint,
    percent numeric(5,2),
    constraint product_cost_items_name_length check (length(btrim(name)) between 1 and 200),
    constraint product_cost_items_value check (
        num_nonnulls(amount, percent) = 1 and coalesce(amount, 0) >= 0 and coalesce(percent, 0) between 0 and 99
    )
);

alter table public.cost_settings
    add constraint cost_settings_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;
alter table public.overhead_items
    add constraint overhead_items_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;
alter table public.product_cost_items
    add constraint product_cost_items_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;
alter table public.product_cost_items
    add constraint product_cost_items_product_id_fkey foreign key (product_id, business_id) references public.products(id, business_id) on delete cascade;

create index overhead_items_business_id_idx on public.overhead_items using btree (business_id);
create index product_cost_items_business_id_idx on public.product_cost_items using btree (business_id);
create index product_cost_items_product_id_idx on public.product_cost_items using btree (product_id);

-- Owners, managers and accountants see costs
CREATE OR REPLACE FUNCTION "public"."can_read_costs"() RETURNS boolean
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$ select coalesce(public.current_business_role() in ('owner', 'manager', 'accountant'), false) $$;

-- Owners and managers change them
CREATE OR REPLACE FUNCTION "public"."can_manage_costs"() RETURNS boolean
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$ select coalesce(public.current_business_role() in ('owner', 'manager'), false) $$;

-- The figures the cost screen needs besides the products: the settings (or
-- their defaults), the expenses of a month, the working minutes of all
-- specialists in a month, the average commission, the last purchase cost of
-- each product and the income tax rates of the country pack.
CREATE OR REPLACE FUNCTION "public"."cost_inputs"() RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  biz_id uuid := public.current_business_id();
  settings public.cost_settings;
begin
  if biz_id is null or not public.can_read_costs() then
    raise exception 'Costs are for owners, managers and accountants' using errcode = '42501';
  end if;
  select * into settings from public.cost_settings s where s.business_id = biz_id;
  if not found then
    settings.business_id := biz_id;
    settings.load_percent := 75;
    settings.pay_mode := 'commission';
    settings.tax_percent := 0;
    settings.card_fee_percent := 0;
    settings.card_share_percent := 0;
    settings.service_price_method := 'margin';
    settings.service_price_value := 30;
    settings.goods_price_method := 'markup';
    settings.goods_price_value := 50;
    settings.price_rounding := 'none';
    settings.material_price := 'average';
  end if;

  return jsonb_build_object(
    'settings', to_jsonb(settings) - 'business_id' - 'updated_at',
    'overhead_monthly', (
        select coalesce(round(sum(case when o.kind = 'monthly' then o.amount else o.amount::numeric / o.months end)), 0)::bigint
        from public.overhead_items o where o.business_id = biz_id),
    -- A month is 52 weeks / 12
    'working_minutes_month', (
        select coalesce(round(sum(extract(epoch from (w.ends_at - w.starts_at)) / 60) * 52 / 12), 0)::bigint
        from public.working_hours w
        join public.sales s on s.id = w.sales_id
        join public.members m on m.user_id = s.user_id and m.business_id = w.business_id and not m.disabled
        where w.business_id = biz_id),
    'commission_percent', (
        select round(avg(m.commission_percent), 2)
        from public.members m
        where m.business_id = biz_id and not m.disabled and m.commission_percent is not null),
    'last_costs', (
        select coalesce(jsonb_object_agg(l.product_id::text, l.unit_cost), '{}'::jsonb)
        from (
            select distinct on (m.product_id) m.product_id, m.unit_cost
            from public.stock_moves m
            where m.business_id = biz_id and m.kind = 'receipt'
              and not exists (select 1 from public.stock_moves r where r.reverses_id = m.id)
            order by m.product_id, m.moved_at desc, m.id desc
        ) l),
    'income_taxes', (
        select coalesce(jsonb_agg(jsonb_build_object('code', t.code, 'rate', t.rate, 'label', t.label) order by t.rate desc), '[]'::jsonb)
        from public.tax_rates t
        join public.businesses b on b.country_code = t.country_code
        where b.id = biz_id and t.tax = 'income'
          and t.valid_from <= current_date and (t.valid_to is null or t.valid_to > current_date))
  );
end;
$$;

-- Keeps the time of the last change of the settings
CREATE OR REPLACE FUNCTION "public"."touch_cost_settings"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create or replace trigger touch_cost_settings
    before update on public.cost_settings
    for each row execute function public.touch_cost_settings();

