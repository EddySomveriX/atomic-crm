--
-- The public booking page of a business (/book/<slug>): its address and the
-- texts it shows, kept by the owner; it is off until the owner turns it on.
-- Clients prove their phone number with a one-time SMS code (phone_codes);
-- a proven phone gets a key for 30 days (booking_sessions). Codes and keys
-- are stored as SHA-256 hashes only, and both tables are read and written by
-- the server alone.
--

create table public.booking_pages (
    business_id uuid not null default public.current_business_id() primary key,
    created_at timestamp with time zone not null default now(),
    -- The address of the page: /book/<slug>
    slug text not null,
    enabled boolean not null default false,
    about text,
    address text,
    phone text,
    -- Instagram username, without the @
    instagram text,
    constraint booking_pages_slug_format check (slug ~ '^[a-z0-9](?:[a-z0-9-]{1,38}[a-z0-9])$'),
    constraint booking_pages_slug_key unique (slug),
    constraint booking_pages_about_length check (about is null or length(about) <= 1000),
    constraint booking_pages_address_length check (address is null or length(address) <= 300),
    constraint booking_pages_phone_length check (phone is null or length(phone) <= 32),
    constraint booking_pages_instagram_format check (instagram is null or instagram ~ '^[A-Za-z0-9._]{1,30}$')
);

-- Read by the server only: no access for signed-in users
create table public.phone_codes (
    id bigint generated by default as identity primary key,
    business_id uuid not null,
    created_at timestamp with time zone not null default now(),
    -- Digits of the phone number, without the +
    phone text not null,
    code_hash text not null,
    expires_at timestamp with time zone not null,
    attempts smallint not null default 0,
    used_at timestamp with time zone,
    constraint phone_codes_phone_format check (phone ~ '^\d{7,15}$')
);

-- Read by the server only
create table public.booking_sessions (
    id bigint generated by default as identity primary key,
    business_id uuid not null,
    created_at timestamp with time zone not null default now(),
    phone text not null,
    token_hash text not null,
    expires_at timestamp with time zone not null,
    constraint booking_sessions_phone_format check (phone ~ '^\d{7,15}$'),
    constraint booking_sessions_token_hash_key unique (token_hash)
);

alter table public.booking_pages
    add constraint booking_pages_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;
alter table public.phone_codes
    add constraint phone_codes_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;
alter table public.booking_sessions
    add constraint booking_sessions_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;

create index phone_codes_business_id_phone_idx on public.phone_codes using btree (business_id, phone, created_at);
create index booking_sessions_business_id_idx on public.booking_sessions using btree (business_id);

alter table public.bookings drop constraint bookings_source;
alter table public.bookings
    add constraint bookings_source check (source in ('crm', 'telegram', 'widget', 'instagram', 'messenger', 'whatsapp', 'viber', 'page'));

--
-- Access
--

alter table public.booking_pages enable row level security;
alter table public.phone_codes enable row level security;
alter table public.booking_sessions enable row level security;

create policy "Business read" on public.booking_pages for select to authenticated using (business_id = (select public.current_business_id()));
create policy "Owner insert" on public.booking_pages for insert to authenticated with check (business_id = (select public.current_business_id()) and (select public.is_admin()));
create policy "Owner update" on public.booking_pages for update to authenticated using (business_id = (select public.current_business_id()) and (select public.is_admin())) with check (business_id = (select public.current_business_id()));

grant select, insert, update on table public.booking_pages to authenticated;
grant all on table public.booking_pages to service_role;
revoke all on table public.phone_codes from anon, authenticated;
revoke all on table public.booking_sessions from anon, authenticated;
grant all on table public.phone_codes to service_role;
grant all on table public.booking_sessions to service_role;
