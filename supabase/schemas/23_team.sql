create table public.day_closings (
    id bigint generated by default as identity primary key,
    business_id uuid not null default public.current_business_id(),
    day date not null,
    closed_at timestamp with time zone not null default now(),
    closed_by uuid default auth.uid(),
    -- visits, no_shows, cancelled, revenue and per specialist
    totals jsonb not null,
    constraint day_closings_business_id_day_key unique (business_id, day)
);

alter table public.day_closings
    add constraint day_closings_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;

-- Closes a day of the business once every visit is marked; closing again
-- after a correction updates the totals. Owners and managers.
CREATE OR REPLACE FUNCTION "public"."close_day"("p_day" "date") RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  v_business uuid := public.current_business_id();
  v_timezone text;
  v_totals jsonb;
begin
  if not public.can_manage_booking() then
    raise exception 'Only owners and managers close the day' using errcode = '42501';
  end if;
  select b.timezone into v_timezone from public.businesses b where b.id = v_business;
  if p_day > (now() at time zone v_timezone)::date then
    raise exception 'A day is closed once it has come' using errcode = '22023';
  end if;
  if exists (
      select 1 from public.bookings bk
      where bk.business_id = v_business and bk.status = 'booked'
        and (bk.starts_at at time zone v_timezone)::date = p_day) then
    raise exception 'Some visits of the day are not marked' using errcode = 'P0001';
  end if;
  select jsonb_build_object(
      'visits', coalesce(sum(r.visits), 0),
      'no_shows', coalesce(sum(r.no_shows), 0),
      'revenue', coalesce(sum(r.revenue), 0),
      'commission', coalesce(sum(r.commission), 0),
      'cancelled', (
          select count(*) from public.bookings bk
          where bk.business_id = v_business and bk.status = 'cancelled'
            and (bk.starts_at at time zone v_timezone)::date = p_day),
      'specialists', coalesce(jsonb_agg(jsonb_build_object(
          'sales_id', r.sales_id, 'name', btrim(r.first_name || ' ' || r.last_name),
          'visits', r.visits, 'revenue', r.revenue, 'commission', r.commission))
          filter (where r.visits > 0 or r.no_shows > 0), '[]'::jsonb))
  into v_totals
  from public.team_report(p_day, p_day) r;
  insert into public.day_closings (business_id, day, totals)
  values (v_business, p_day, v_totals)
  on conflict (business_id, day) do update
    set totals = excluded.totals, closed_at = now(), closed_by = auth.uid();
  return v_totals;
end;
$$;

