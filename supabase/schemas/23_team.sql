-- Who of the team gets messages; a member unlinks themselves, an owner anyone
create policy "Business read" on public.staff_telegram for select to authenticated using (business_id = (select public.current_business_id()));
create policy "Self or owner unlink" on public.staff_telegram for delete to authenticated using (business_id = (select public.current_business_id()) and ((select public.is_admin()) or sales_id = (select s.id from public.sales s where s.user_id = (select auth.uid()))));
-- Codes and the queue are the server's: no policies
create policy "Business read" on public.day_closings for select to authenticated using (business_id = (select public.current_business_id()));

