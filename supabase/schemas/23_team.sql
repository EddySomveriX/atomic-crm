--
-- The team (third batch of improvements):
--   * a member links their Telegram to the bot of the business with a
--     one-time code and gets a message when a booking of theirs is made,
--     moved or cancelled by someone else;
--   * a member's commission, a percent of the visits they completed, and a
--     report of visits, revenue and commission for a period;
--   * "close the day": every visit of the day marked, and the totals of the
--     day kept.
--

alter table public.members
    add column commission_percent numeric(5,2);
alter table public.members
    add constraint members_commission_percent check (commission_percent between 0 and 100);

--
-- Telegram of the team
--

create table public.staff_telegram (
    business_id uuid not null,
    sales_id bigint not null,
    chat_id text not null,
    linked_at timestamp with time zone not null default now(),
    primary key (business_id, sales_id)
);

alter table public.staff_telegram
    add constraint staff_telegram_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;
alter table public.staff_telegram
    add constraint staff_telegram_sales_id_fkey foreign key (sales_id) references public.sales(id) on delete cascade;

-- One-time codes a member sends to the bot to link their Telegram
create table public.staff_link_codes (
    code text primary key,
    business_id uuid not null,
    sales_id bigint not null,
    expires_at timestamp with time zone not null,
    constraint staff_link_codes_code check (code ~ '^[A-Z2-9]{8}$')
);

alter table public.staff_link_codes
    add constraint staff_link_codes_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;
alter table public.staff_link_codes
    add constraint staff_link_codes_sales_id_fkey foreign key (sales_id) references public.sales(id) on delete cascade;

-- Messages to members about their bookings, sent by the server
create table public.staff_notifications (
    id bigint generated by default as identity primary key,
    business_id uuid not null,
    created_at timestamp with time zone not null default now(),
    sales_id bigint not null,
    booking_id bigint not null,
    kind text not null,
    status text not null default 'pending',
    sent_at timestamp with time zone,
    error text,
    constraint staff_notifications_kind check (kind in ('new', 'moved', 'cancelled')),
    constraint staff_notifications_status check (status in ('pending', 'sent', 'failed'))
);

alter table public.staff_notifications
    add constraint staff_notifications_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;
alter table public.staff_notifications
    add constraint staff_notifications_booking_id_fkey foreign key (booking_id, business_id) references public.bookings(id, business_id) on delete cascade;
create index staff_notifications_pending_idx on public.staff_notifications using btree (created_at) where status = 'pending';
create index staff_notifications_booking_id_idx on public.staff_notifications using btree (booking_id);

-- A code for the current member, valid for 15 minutes
CREATE OR REPLACE FUNCTION "public"."create_staff_link_code"() RETURNS "text"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  v_business uuid := public.current_business_id();
  v_sales bigint;
  v_code text;
begin
  select s.id into v_sales from public.sales s where s.user_id = auth.uid();
  if v_business is null or v_sales is null then
    raise exception 'No current business' using errcode = '42501';
  end if;
  delete from public.staff_link_codes where sales_id = v_sales or expires_at < now();
  v_code := (
    select string_agg(substr('ABCDEFGHJKLMNPQRSTUVWXYZ23456789', 1 + floor(random() * 32)::int, 1), '')
    from generate_series(1, 8)
  );
  insert into public.staff_link_codes (code, business_id, sales_id, expires_at)
  values (v_code, v_business, v_sales, now() + interval '15 minutes');
  return v_code;
end;
$$;

-- The bot links the chat that sent a valid code; returns the member's first
-- name, or null for an unknown or expired code. Server only.
CREATE OR REPLACE FUNCTION "public"."link_staff_telegram"("p_business_id" "uuid", "p_code" "text", "p_chat_id" "text") RETURNS "text"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  v_sales bigint;
begin
  delete from public.staff_link_codes c
  where c.code = upper(p_code) and c.business_id = p_business_id and c.expires_at > now()
  returning c.sales_id into v_sales;
  if v_sales is null then
    return null;
  end if;
  insert into public.staff_telegram (business_id, sales_id, chat_id)
  values (p_business_id, v_sales, p_chat_id)
  on conflict (business_id, sales_id) do update set chat_id = excluded.chat_id, linked_at = now();
  return (select s.first_name from public.sales s where s.id = v_sales);
end;
$$;

-- Queues a message to the specialist of a booking when someone else makes,
-- moves or cancels it
CREATE OR REPLACE FUNCTION "public"."queue_staff_notification"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  v_author bigint := (select s.id from public.sales s where s.user_id = auth.uid());
begin
  if tg_op = 'INSERT' then
    if new.status = 'booked' and new.sales_id is distinct from v_author then
      insert into public.staff_notifications (business_id, sales_id, booking_id, kind)
      select new.business_id, new.sales_id, new.id, 'new'
      where exists (select 1 from public.staff_telegram t where t.business_id = new.business_id and t.sales_id = new.sales_id);
    end if;
    return new;
  end if;
  if new.status = 'cancelled' and old.status = 'booked' then
    insert into public.staff_notifications (business_id, sales_id, booking_id, kind)
    select new.business_id, old.sales_id, new.id, 'cancelled'
    where old.sales_id is distinct from v_author
      and exists (select 1 from public.staff_telegram t where t.business_id = new.business_id and t.sales_id = old.sales_id);
  elsif new.status = 'booked' and new.sales_id <> old.sales_id then
    insert into public.staff_notifications (business_id, sales_id, booking_id, kind)
    select new.business_id, x.sales_id, new.id, x.kind
    from (values (old.sales_id, 'cancelled'), (new.sales_id, 'new')) as x(sales_id, kind)
    where x.sales_id is distinct from v_author
      and exists (select 1 from public.staff_telegram t where t.business_id = new.business_id and t.sales_id = x.sales_id);
  elsif new.status = 'booked' and new.starts_at <> old.starts_at then
    insert into public.staff_notifications (business_id, sales_id, booking_id, kind)
    select new.business_id, new.sales_id, new.id, 'moved'
    where new.sales_id is distinct from v_author
      and exists (select 1 from public.staff_telegram t where t.business_id = new.business_id and t.sales_id = new.sales_id);
  end if;
  return new;
end;
$$;

create or replace trigger queue_staff_notification
    after insert or update of status, starts_at, sales_id on public.bookings
    for each row execute function public.queue_staff_notification();

