--
-- Price list, offers, packages and gift certificates (the "Прайс" module)
-- The price of a product is the single source: the bot, the website widget
-- and the calendar read it at the moment of booking, and a booking keeps
-- the price it was made at. A specialist can have an own price for a
-- service. Offers lower the price automatically; only one applies, the best
-- for the client. A client who holds a package for a service books it at no
-- price, and a completed visit uses one visit of the package. Gift
-- certificates hold an amount (or one service) spent on bookings; every use
-- is a record that is never changed, only reversed.
--

