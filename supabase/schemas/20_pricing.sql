    add constraint businesses_modules check (modules <@ array['chats', 'booking', 'sales', 'stock', 'tasks', 'analytics', 'pricing']);

CREATE OR REPLACE FUNCTION "public"."default_modules"("p_business_type" "text") RETURNS "text"[]
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
    select case p_business_type
        when 'services' then array['chats', 'booking', 'pricing', 'tasks', 'analytics']
        when 'retail' then array['chats', 'sales', 'stock', 'pricing', 'analytics']
        when 'production' then array['sales', 'stock', 'tasks', 'analytics']
        when 'b2b' then array['chats', 'sales', 'tasks', 'analytics']
        else array['chats', 'booking', 'sales', 'stock', 'tasks', 'analytics', 'pricing']
    end
$$;

