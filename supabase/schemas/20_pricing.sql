-- Owners and managers keep the price list, offers and packages
CREATE OR REPLACE FUNCTION "public"."can_manage_prices"() RETURNS boolean
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$ select coalesce(public.current_business_role() in ('owner', 'manager'), false) $$;

CREATE OR REPLACE FUNCTION "public"."record_price_change"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if new.price is distinct from old.price then
    insert into public.price_history (business_id, product_id, old_price, new_price)
    values (new.business_id, new.id, old.price, new.price);
  end if;
  return new;
end;
$$;

-- Changes the prices of several products by a percent, rounded to whole
-- units of money; returns how many changed. Owners and managers only.
CREATE OR REPLACE FUNCTION "public"."change_prices"("p_product_ids" bigint[], "p_percent" numeric) RETURNS integer
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  changed integer;
begin
  if not public.can_manage_prices() then
    raise exception 'Only owners and managers change prices' using errcode = '42501';
  end if;
  if p_percent < -90 or p_percent > 500 or p_percent = 0 then
    raise exception 'The percent is out of range' using errcode = '22023';
  end if;
  update public.products p
  set price = round(p.price * (100 + p_percent) / 100 / 100) * 100
  where p.id = any(p_product_ids) and p.price is not null
    and p.business_id = public.current_business_id();
  get diagnostics changed = row_count;
  return changed;
end;
$$;

-- The price of a service for a booking: the own price of the specialist or
-- the list price, then the best single offer for this client and time.
-- Security definer so that the bot (service role) and members get the same
-- answer; it reads the given business only.
CREATE OR REPLACE FUNCTION "public"."price_quote"("p_business_id" "uuid", "p_product_id" bigint, "p_sales_id" bigint, "p_starts_at" timestamp with time zone, "p_client_id" bigint DEFAULT NULL::bigint, "p_code" "text" DEFAULT NULL::"text") RETURNS TABLE("list_price" bigint, "price" bigint, "promotion_id" bigint, "promotion_name" "text", "percent" integer)
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  base bigint;
  tz text;
  local_start timestamp;
  best_percent integer := 0;
  best_id bigint;
  best_name text;
  personal integer;
  is_new boolean;
begin
  select coalesce(sp.price, p.price), b.timezone into base, tz
  from public.products p
  join public.businesses b on b.id = p.business_id
  left join public.specialist_prices sp on sp.product_id = p.id and sp.sales_id = p_sales_id
  where p.id = p_product_id and p.business_id = p_business_id;
  if base is null then
    return query select null::bigint, null::bigint, null::bigint, null::text, null::integer;
    return;
  end if;
  local_start := p_starts_at at time zone tz;
  is_new := p_client_id is null or not exists (
      select 1 from public.bookings bk
      where bk.client_id = p_client_id and bk.business_id = p_business_id and bk.status = 'completed');

  select pr.id, pr.name, pr.percent into best_id, best_name, best_percent
  from public.promotions pr
  where pr.business_id = p_business_id and pr.active
    and (cardinality(pr.product_ids) = 0 or p_product_id = any(pr.product_ids))
    and (pr.valid_from is null or local_start::date >= pr.valid_from)
    and (pr.valid_to is null or local_start::date <= pr.valid_to)
    and case pr.kind
        when 'happy_hours' then extract(isodow from local_start)::smallint = any(pr.weekdays)
            and local_start::time >= pr.time_from and local_start::time < pr.time_to
        when 'last_minute' then p_starts_at <= now() + make_interval(hours => pr.within_hours)
        when 'first_visit' then is_new
        when 'promo_code' then p_code is not null and upper(btrim(p_code)) = pr.code
            and (pr.max_uses is null or pr.used_count < pr.max_uses)
        else false
    end
  order by pr.percent desc, pr.id
  limit 1;

  select c.personal_discount into personal
  from public.companies c where c.id = p_client_id and c.business_id = p_business_id;
  if coalesce(personal, 0) > coalesce(best_percent, 0) then
    best_percent := personal;
    best_id := null;
    best_name := null;
  end if;

  return query select base,
      base - round(base * coalesce(best_percent, 0) / 100.0 / 100) ::bigint * 100,
      best_id, best_name, nullif(coalesce(best_percent, 0), 0);
end;
$$;

-- A new booking gets its price; a client's active package for the service
-- pays for it instead. A change of service, specialist or time re-prices a
-- booking that is still ahead.
CREATE OR REPLACE FUNCTION "public"."price_booking"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  quote record;
  package_id bigint;
begin
  if tg_op = 'UPDATE'
     and new.product_id = old.product_id and new.sales_id = old.sales_id
     and new.starts_at = old.starts_at
     and new.promo_code is not distinct from old.promo_code
     and new.client_id is not distinct from old.client_id then
    return new;
  end if;
  if tg_op = 'UPDATE' and old.status <> 'booked' then
    return new;
  end if;

  if new.client_id is not null and (tg_op = 'INSERT' or new.client_package_id is null) then
    select cp.id into package_id
    from public.client_packages cp
    where cp.client_id = new.client_id and cp.business_id = new.business_id
      and cp.product_id = new.product_id and cp.status = 'active'
      and cp.visits_left > 0 and cp.expires_at > new.starts_at
    order by cp.expires_at
    limit 1;
    new.client_package_id := coalesce(new.client_package_id, package_id);
  end if;

  select * into quote from public.price_quote(new.business_id, new.product_id, new.sales_id, new.starts_at, new.client_id, new.promo_code);
  new.list_price := quote.list_price;
  if new.client_package_id is not null then
    new.price := 0;
    new.promotion_id := null;
  else
    new.price := quote.price;
    new.promotion_id := quote.promotion_id;
  end if;
  if new.promo_code is not null and new.promotion_id is not null
     and (tg_op = 'INSERT' or new.promo_code is distinct from old.promo_code) then
    update public.promotions set used_count = used_count + 1
    where id = new.promotion_id and kind = 'promo_code';
  end if;
  return new;
end;
$$;

-- A completed visit uses one visit of its package; undoing the completion
-- gives it back.
CREATE OR REPLACE FUNCTION "public"."use_package_visit"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if new.client_package_id is null then
    return new;
  end if;
  if new.status = 'completed' and not new.package_visit_used then
    update public.client_packages set visits_left = visits_left - 1
    where id = new.client_package_id and visits_left > 0;
    if not found then
      raise exception 'The package has no visits left' using errcode = '23514';
    end if;
    new.package_visit_used := true;
  elsif new.status <> 'completed' and new.package_visit_used then
    update public.client_packages set visits_left = visits_left + 1
    where id = new.client_package_id;
    new.package_visit_used := false;
  end if;
  return new;
end;
$$;

-- A certificate sold gets a random code and its full balance
CREATE OR REPLACE FUNCTION "public"."prepare_certificate"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  candidate text;
begin
  if new.code is null then
    loop
      select string_agg(substr(alphabet, 1 + floor(random() * length(alphabet))::int, 1), '')
        into candidate from generate_series(1, 8);
      exit when not exists (
          select 1 from public.gift_certificates g
          where g.business_id = new.business_id and g.code = candidate);
    end loop;
    new.code := candidate;
  end if;
  new.balance := new.amount;
  return new;
end;
$$;

-- A use spends the balance of the certificate (an amount) or the
-- certificate itself (a service); a reversal gives it back
CREATE OR REPLACE FUNCTION "public"."apply_certificate_use"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  certificate public.gift_certificates;
begin
  select * into certificate from public.gift_certificates
  where id = new.certificate_id for update;
  if new.reverses_id is null then
    if certificate.status <> 'active' or certificate.expires_at < now() then
      raise exception 'The certificate is not valid' using errcode = '23514';
    end if;
    if new.amount <= 0 or (certificate.amount is not null and new.amount > certificate.balance) then
      raise exception 'The certificate has not enough left' using errcode = '23514';
    end if;
  else
    if not exists (select 1 from public.certificate_uses u
                   where u.id = new.reverses_id and u.certificate_id = new.certificate_id
                     and u.amount = -new.amount and u.reverses_id is null) then
      raise exception 'A reversal mirrors a use of the same certificate' using errcode = '23514';
    end if;
  end if;
  if certificate.amount is not null then
    update public.gift_certificates
    set balance = balance - new.amount,
        status = case when balance - new.amount = 0 then 'used' else 'active' end
    where id = new.certificate_id;
  else
    update public.gift_certificates
    set status = case when new.amount > 0 then 'used' else 'active' end
    where id = new.certificate_id;
  end if;
  return new;
end;
$$;

-- Records of sales and uses are never deleted
CREATE OR REPLACE FUNCTION "public"."protect_money_record"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if not exists (select 1 from public.businesses b where b.id = old.business_id) then
    return old;
  end if;
  raise exception 'Sold packages, certificates and their uses are cancelled, never deleted'
    using errcode = '42501';
end;
$$;

