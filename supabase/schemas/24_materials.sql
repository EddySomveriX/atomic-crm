--
-- Materials per service
-- A service lists the goods and materials one visit uses up. When a booking
-- of the service is completed they are written off the default warehouse as
-- issue moves that point to the booking, at the average cost of the moment;
-- when the booking stops being completed (or is deleted) those moves are
-- reversed. Only what is in stock is written off: a visit never fails for
-- want of stock. The cost of the moves gives the margin of visits.
--

create table public.service_materials (
    id bigint generated by default as identity primary key,
    business_id uuid not null default public.current_business_id(),
    created_at timestamp with time zone not null default now(),
    service_id bigint not null,
    material_id bigint not null,
    -- Quantity used by one visit, in the unit of the material
    quantity numeric(14,3) not null,
    constraint service_materials_quantity check (quantity > 0),
    constraint service_materials_service_id_material_id_key unique (service_id, material_id)
);

-- The booking a write-off belongs to (no foreign key: a deleted booking
-- keeps its posted moves, which are reversed by the trigger below)
alter table public.stock_moves add column booking_id bigint;

alter table public.service_materials
    add constraint service_materials_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;
alter table public.service_materials
    add constraint service_materials_service_id_fkey foreign key (service_id, business_id) references public.products(id, business_id) on delete cascade;
alter table public.service_materials
    add constraint service_materials_material_id_fkey foreign key (material_id, business_id) references public.products(id, business_id) on delete cascade;

create index service_materials_business_id_idx on public.service_materials using btree (business_id);
create index service_materials_material_id_idx on public.service_materials using btree (material_id);
create index stock_moves_booking_id_idx on public.stock_moves using btree (booking_id) where booking_id is not null;

-- A service uses goods or materials, never another service
CREATE OR REPLACE FUNCTION "public"."check_service_material"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if not exists (select 1 from public.products p
                 where p.id = new.service_id and p.business_id = new.business_id and p.kind = 'service') then
    raise exception 'Materials belong to a service' using errcode = '23514';
  end if;
  if not exists (select 1 from public.products p
                 where p.id = new.material_id and p.business_id = new.business_id and p.kind in ('goods', 'material')) then
    raise exception 'A service uses goods or materials' using errcode = '23514';
  end if;
  return new;
end;
$$;

-- Reverses the write-offs of a booking that were not reversed yet
CREATE OR REPLACE FUNCTION "public"."return_booking_materials"("p_business_id" "uuid", "p_booking_id" bigint) RETURNS void
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  insert into public.stock_moves (business_id, kind, product_id, to_warehouse_id, quantity, currency, note, reverses_id, booking_id)
  select m.business_id, 'reversal', m.product_id, m.from_warehouse_id, m.quantity, m.currency, m.note, m.id, m.booking_id
  from public.stock_moves m
  where m.business_id = p_business_id and m.booking_id = p_booking_id and m.kind = 'issue'
    and not exists (select 1 from public.stock_moves r where r.reverses_id = m.id)
  order by m.id;
end;
$$;

-- Writes off the materials of a completed booking, returns them when the
-- booking is no longer completed
CREATE OR REPLACE FUNCTION "public"."write_off_materials"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  warehouse_id bigint;
  item record;
  available numeric;
begin
  if tg_op = 'DELETE' then
    if old.status = 'completed' and exists (select 1 from public.businesses b where b.id = old.business_id) then
      perform public.return_booking_materials(old.business_id, old.id);
    end if;
    return old;
  end if;
  if tg_op = 'UPDATE' and new.status is not distinct from old.status then
    return new;
  end if;
  if tg_op = 'UPDATE' and old.status = 'completed' then
    perform public.return_booking_materials(new.business_id, new.id);
  end if;
  if new.status <> 'completed' then
    return new;
  end if;

  select w.id into warehouse_id from public.warehouses w
  where w.business_id = new.business_id and w.is_default;
  if warehouse_id is null then
    return new;
  end if;
  for item in
    select sm.material_id, sm.quantity
    from public.service_materials sm
    where sm.business_id = new.business_id and sm.service_id = new.product_id
    order by sm.material_id
  loop
    available := public.stock_quantity(item.material_id, warehouse_id);
    if available > 0 then
      insert into public.stock_moves (business_id, kind, product_id, from_warehouse_id, quantity, unit_cost, note, booking_id)
      select new.business_id, 'issue', item.material_id, warehouse_id, least(item.quantity, available), s.average_cost, null, new.id
      from public.products_summary s
      where s.id = item.material_id;
    end if;
  end loop;
  return new;
end;
$$;

create or replace trigger check_service_material
    before insert or update on public.service_materials
    for each row execute function public.check_service_material();

create or replace trigger write_off_materials
    after insert or update of status or delete on public.bookings
    for each row execute function public.write_off_materials();

--
-- Access
--

alter table public.service_materials enable row level security;

create policy "Business read" on public.service_materials for select to authenticated using (business_id = (select public.current_business_id()));
create policy "Stock insert" on public.service_materials for insert to authenticated with check (business_id = (select public.current_business_id()) and (select public.can_manage_stock()));
create policy "Stock update" on public.service_materials for update to authenticated using (business_id = (select public.current_business_id()) and (select public.can_manage_stock())) with check (business_id = (select public.current_business_id()));
create policy "Stock delete" on public.service_materials for delete to authenticated using (business_id = (select public.current_business_id()) and (select public.can_manage_stock()));

grant select, insert, update, delete on table public.service_materials to authenticated;
grant all on table public.service_materials to service_role;
grant usage, select on sequence public.service_materials_id_seq to authenticated;
grant all on sequence public.service_materials_id_seq to service_role;

revoke all on function public.return_booking_materials(uuid, bigint) from public, anon, authenticated;
grant all on function public.return_booking_materials(uuid, bigint) to service_role;
