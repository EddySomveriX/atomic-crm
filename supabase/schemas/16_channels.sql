--
-- Channels and the chat center (TZ sections 5.2 and 9)
-- A business connects channels (its Telegram bot, the widget of its
-- website); each chat with a client is a conversation tied to a
-- counterparty, with its messages in one feed. Secrets of a channel (the bot
-- token) live in channel_secrets, which only the server reads. Deliveries of
-- the channel are recorded in channel_events, so a repeated delivery of the
-- same update is processed once.
--

create table public.channels (
    id bigint generated by default as identity primary key,
    business_id uuid not null default public.current_business_id(),
    created_at timestamp with time zone not null default now(),
    kind text not null,
    -- Telegram: the username of the bot; widget: empty
    name text,
    -- Public key of the website widget, written in the snippet of the site
    public_key uuid not null default gen_random_uuid(),
    enabled boolean not null default true,
    constraint channels_kind check (kind in ('telegram', 'widget')),
    constraint channels_name_length check (name is null or length(name) <= 100),
    constraint channels_public_key_key unique (public_key),
    constraint channels_business_id_kind_key unique (business_id, kind),
    constraint channels_id_business_id_key unique (id, business_id)
);

-- Read by the server only: no access for signed-in users
create table public.channel_secrets (
    channel_id bigint not null primary key,
    bot_token text,
    -- Telegram sends it back in a header with every webhook delivery
    webhook_secret text,
    -- Next Telegram update to fetch when polling (local development)
    update_offset bigint not null default 0
);

create table public.channel_events (
    channel_id bigint not null,
    event_id text not null,
    received_at timestamp with time zone not null default now(),
    primary key (channel_id, event_id)
);

create table public.conversations (
    id bigint generated by default as identity primary key,
    business_id uuid not null default public.current_business_id(),
    created_at timestamp with time zone not null default now(),
    channel_id bigint not null,
    -- Telegram chat id, or the visitor id of the website widget
    external_id text not null,
    -- Name of the client in the channel
    title text,
    phone text,
    -- The client: a counterparty
    client_id bigint,
    -- The member who answers
    assigned_to bigint,
    status text not null default 'open',
    -- Language of the client: uk or en
    language text not null default 'uk',
    consent_at timestamp with time zone,
    last_message_at timestamp with time zone,
    -- Since when the client waits for an answer of a person (empty: answered)
    waiting_since timestamp with time zone,
    -- Where the client is in the booking dialog of the bot
    bot_state jsonb not null default '{}'::jsonb,
    constraint conversations_status check (status in ('open', 'closed')),
    constraint conversations_language check (language in ('uk', 'en')),
    constraint conversations_title_length check (title is null or length(title) <= 200),
    constraint conversations_phone_length check (phone is null or length(phone) <= 32),
    constraint conversations_bot_state_is_object check (jsonb_typeof(bot_state) = 'object'),
    constraint conversations_channel_id_external_id_key unique (channel_id, external_id),
    constraint conversations_id_business_id_key unique (id, business_id)
);

create table public.messages (
    id bigint generated by default as identity primary key,
    business_id uuid not null,
    created_at timestamp with time zone not null default now(),
    conversation_id bigint not null,
    direction text not null,
    -- Who wrote an outgoing message: a member, or the bot when empty
    sales_id bigint,
    body text not null,
    -- An incoming message the bot answered by itself (a button of the
    -- booking dialog): it does not wait for a person
    handled_by_bot boolean not null default false,
    -- Id of the message in the channel
    external_id text,
    status text not null default 'sent',
    error text,
    constraint messages_direction check (direction in ('in', 'out')),
    constraint messages_body_length check (length(body) between 1 and 4096),
    constraint messages_status check (status in ('received', 'pending', 'sent', 'failed')),
    constraint messages_conversation_id_direction_external_id_key unique (conversation_id, direction, external_id)
);

create table public.reply_templates (
    id bigint generated by default as identity primary key,
    business_id uuid not null default public.current_business_id(),
    created_at timestamp with time zone not null default now(),
    title text not null,
    body text not null,
    constraint reply_templates_title_length check (length(btrim(title)) between 1 and 100),
    constraint reply_templates_body_length check (length(btrim(body)) between 1 and 4096)
);

