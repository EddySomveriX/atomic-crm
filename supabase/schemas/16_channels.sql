-- Rules
--

-- A new message moves its conversation up the feed. An incoming message the
-- bot did not answer makes the client wait for a person; an answer of a
-- person ends the wait. An incoming message reopens a closed conversation.
CREATE OR REPLACE FUNCTION "public"."handle_message_created"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  update public.conversations c
  set last_message_at = new.created_at,
      -- Opens the 24 hours in which Instagram, Messenger and WhatsApp let a business answer
      last_inbound_at = case when new.direction = 'in' then new.created_at else c.last_inbound_at end,
      waiting_since = case
          when new.direction = 'in' and not new.handled_by_bot then coalesce(c.waiting_since, new.created_at)
          when new.direction = 'out' and new.sales_id is not null then null
          else c.waiting_since
      end,
      status = case when new.direction = 'in' then 'open' else c.status end
  where c.id = new.conversation_id;
  return new;
end;
$$;

-- The client of a phone number in a business: the counterparty with the same
-- digits, or a new private person with the client role. Server only.
CREATE OR REPLACE FUNCTION "public"."find_or_create_client"("p_business_id" "uuid", "p_name" "text", "p_phone" "text") RETURNS bigint
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  digits text := regexp_replace(coalesce(p_phone, ''), '\D', '', 'g');
  found_id bigint;
begin
  if length(digits) < 7 then
    raise exception 'A phone number has at least 7 digits' using errcode = '22023';
  end if;
  select c.id into found_id
  from public.companies c
  where c.business_id = p_business_id
    and regexp_replace(coalesce(c.phone_number, ''), '\D', '', 'g') = digits
  order by c.id
  limit 1;
  if found_id is not null then
    return found_id;
  end if;

  insert into public.companies (business_id, name, phone_number, kind, roles, country_code)
  select p_business_id, coalesce(nullif(btrim(p_name), ''), '+' || digits), '+' || digits, 'person', '{client}', b.country_code
  from public.businesses b
  where b.id = p_business_id
  returning id into found_id;
  return found_id;
end;
$$;

-- Bookings due for a reminder 24 hours or 2 hours before they start, claimed
-- once: the reminder time is written before the reminder is sent, so a
-- second run never sends it again. A booking made less than 24 (2) hours
-- ahead gets no 24-hour (2-hour) reminder. The conversation is the one the
-- booking was made in, or the latest conversation of the client the
-- business may write in (public.chat_reachable).
-- Server only.
CREATE OR REPLACE FUNCTION "public"."claim_due_reminders"("p_now" timestamp with time zone DEFAULT now()) RETURNS TABLE("booking_id" bigint, "kind" "text", "conversation_id" bigint)
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  return query
  with due as (
      select b.id, '24h'::text as kind
      from public.bookings b
      where b.status = 'booked' and b.reminded_24h_at is null
        and b.starts_at > p_now + interval '2 hours'
        and b.starts_at <= p_now + interval '24 hours'
        and b.created_at <= b.starts_at - interval '24 hours'
      union all
      select b.id, '2h'::text
      from public.bookings b
      where b.status = 'booked' and b.reminded_2h_at is null
        and b.starts_at > p_now
        and b.starts_at <= p_now + interval '2 hours'
        and b.created_at <= b.starts_at - interval '2 hours'
  ),
  claimed as (
      update public.bookings b
      set reminded_24h_at = case when d.kind = '24h' then p_now else b.reminded_24h_at end,
          reminded_2h_at = case when d.kind = '2h' then p_now else b.reminded_2h_at end
      from due d
      where b.id = d.id
      returning b.id, d.kind, b.conversation_id, b.client_id, b.business_id
  )
  -- The conversation the booking was made in while the business may still
  -- write there, else the latest conversation of the client it may write in
  select c.id, c.kind, coalesce((
      select cv.id
      from public.conversations cv
      join public.channels ch on ch.id = cv.channel_id
      where cv.business_id = c.business_id and ch.enabled
        and (cv.id = c.conversation_id or cv.client_id = c.client_id)
        and public.chat_reachable(ch.kind, cv.last_inbound_at, p_now)
      order by (cv.id = c.conversation_id) desc nulls last, cv.last_message_at desc nulls last
      limit 1
  ), c.conversation_id)
  from claimed c;
end;
$$;

create or replace trigger handle_message_created
    after insert on public.messages
    for each row execute function public.handle_message_created();

