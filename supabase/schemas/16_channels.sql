-- A bot is connected by the server (it checks the token); the owner adds the
-- website widget, switches channels off or removes them
create policy "Business read" on public.channels for select to authenticated using (business_id = (select public.current_business_id()));
create policy "Owner adds widget" on public.channels for insert to authenticated with check (business_id = (select public.current_business_id()) and (select public.is_admin()) and kind = 'widget');
create policy "Owner update" on public.channels for update to authenticated using (business_id = (select public.current_business_id()) and (select public.is_admin())) with check (business_id = (select public.current_business_id()));
create policy "Owner delete" on public.channels for delete to authenticated using (business_id = (select public.current_business_id()) and (select public.is_admin()));

-- Conversations come from the channels; members assign, link and close them
create policy "Business read" on public.conversations for select to authenticated using (business_id = (select public.current_business_id()));
create policy "Business update" on public.conversations for update to authenticated using (business_id = (select public.current_business_id()) and (select public.can_write_current_business())) with check (business_id = (select public.current_business_id()));

-- Messages are written by the server, which also delivers them
create policy "Business read" on public.messages for select to authenticated using (business_id = (select public.current_business_id()));

create policy "Business read" on public.reply_templates for select to authenticated using (business_id = (select public.current_business_id()));
create policy "Business insert" on public.reply_templates for insert to authenticated with check (business_id = (select public.current_business_id()) and (select public.can_write_current_business()));
create policy "Business update" on public.reply_templates for update to authenticated using (business_id = (select public.current_business_id()) and (select public.can_write_current_business())) with check (business_id = (select public.current_business_id()));
create policy "Business delete" on public.reply_templates for delete to authenticated using (business_id = (select public.current_business_id()) and (select public.can_write_current_business()));
