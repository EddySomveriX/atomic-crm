-- Stage 3.1: booking of services (see supabase/schemas/15_booking.sql)

--
-- Booking of services (TZ sections 5.3 and 9)
-- A service (a product of kind service) has a duration and a pause after it.
-- Specialists are active members of the business with working hours by
-- weekday. A booking holds its specialist from its start until its end plus
-- the pause of the service, and the database refuses two overlapping
-- bookings of one specialist (exclusion constraint, SQLSTATE 23P01).
--

create extension if not exists btree_gist with schema extensions;

alter table public.products add column duration_minutes integer;
alter table public.products add column buffer_minutes integer not null default 0;
alter table public.products
    add constraint products_duration check (duration_minutes is null or (kind = 'service' and duration_minutes between 5 and 720));
alter table public.products
    add constraint products_buffer check (buffer_minutes between 0 and 240);

-- Working hours of a specialist: one or more intervals per ISO weekday
-- (1 Monday .. 7 Sunday), in the time zone of the business
create table public.working_hours (
    id bigint generated by default as identity primary key,
    business_id uuid not null default public.current_business_id(),
    created_at timestamp with time zone not null default now(),
    sales_id bigint not null,
    weekday smallint not null,
    starts_at time without time zone not null,
    ends_at time without time zone not null,
    constraint working_hours_weekday check (weekday between 1 and 7),
    constraint working_hours_order check (ends_at > starts_at),
    constraint working_hours_no_overlap exclude using gist (
        business_id with =,
        sales_id with =,
        weekday with =,
        tsrange(date '2000-01-01' + starts_at, date '2000-01-01' + ends_at) with &&
    )
);

create table public.bookings (
    id bigint generated by default as identity primary key,
    business_id uuid not null default public.current_business_id(),
    created_at timestamp with time zone not null default now(),
    created_by uuid default auth.uid(),
    -- The specialist
    sales_id bigint not null,
    -- The service
    product_id bigint not null,
    -- The client: a counterparty
    client_id bigint,
    starts_at timestamp with time zone not null,
    -- Filled from the duration of the service when left empty
    ends_at timestamp with time zone not null,
    -- The end plus the pause of the service: the specialist is busy until then
    blocked_until timestamp with time zone not null,
    status text not null default 'booked',
    source text not null default 'crm',
    note text,
    reminded_24h_at timestamp with time zone,
    reminded_2h_at timestamp with time zone,
    constraint bookings_status check (status in ('booked', 'completed', 'cancelled', 'no_show')),
    constraint bookings_source check (source in ('crm', 'telegram', 'widget')),
    constraint bookings_order check (ends_at > starts_at and blocked_until >= ends_at),
    constraint bookings_note_length check (note is null or length(note) <= 2000),
    constraint bookings_id_business_id_key unique (id, business_id),
    constraint bookings_no_overlap exclude using gist (
        sales_id with =,
        tstzrange(starts_at, blocked_until) with &&
    ) where (status <> 'cancelled')
);

alter table public.working_hours
    add constraint working_hours_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;
alter table public.working_hours
    add constraint working_hours_sales_id_fkey foreign key (sales_id) references public.sales(id) on delete cascade;
alter table public.bookings
    add constraint bookings_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;
alter table public.bookings
    add constraint bookings_sales_id_fkey foreign key (sales_id) references public.sales(id);
alter table public.bookings
    add constraint bookings_product_id_fkey foreign key (product_id, business_id) references public.products(id, business_id);
alter table public.bookings
    add constraint bookings_client_id_fkey foreign key (client_id, business_id) references public.companies(id, business_id) on delete set null (client_id);

create index working_hours_business_id_idx on public.working_hours using btree (business_id);
create index bookings_business_id_starts_at_idx on public.bookings using btree (business_id, starts_at);
create index bookings_client_id_idx on public.bookings using btree (client_id);

--
-- Rules
--

-- Owners and managers set up booking: working hours of the specialists
CREATE OR REPLACE FUNCTION "public"."can_manage_booking"() RETURNS boolean
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$ select coalesce(public.current_business_role() in ('owner', 'manager'), false) $$;

-- An active member of the business, by their user profile (sales row)
CREATE OR REPLACE FUNCTION "public"."is_active_member"("p_business_id" "uuid", "p_sales_id" bigint) RETURNS boolean
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
    select exists (
        select 1
        from public.sales s
        join public.members m on m.user_id = s.user_id
        where s.id = p_sales_id and m.business_id = p_business_id and not m.disabled
    )
$$;

CREATE OR REPLACE FUNCTION "public"."check_working_hours"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if not public.is_active_member(new.business_id, new.sales_id) then
    raise exception 'The specialist is not a member of this business' using errcode = '23503';
  end if;
  return new;
end;
$$;

-- A booking ends after the duration of its service unless an end is given; a
-- moved booking keeps its length. The pause of the service is added to the
-- time the specialist is busy.
CREATE OR REPLACE FUNCTION "public"."check_booking"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  service record;
begin
  select p.duration_minutes, p.buffer_minutes into service
  from public.products p
  where p.id = new.product_id and p.business_id = new.business_id;
  if not found or service.duration_minutes is null then
    raise exception 'Only a service with a duration can be booked' using errcode = '23514';
  end if;
  if not public.is_active_member(new.business_id, new.sales_id) then
    raise exception 'The specialist is not a member of this business' using errcode = '23503';
  end if;

  if new.ends_at is null then
    new.ends_at := new.starts_at + make_interval(mins => service.duration_minutes);
  elsif tg_op = 'UPDATE' and new.starts_at <> old.starts_at and new.ends_at = old.ends_at then
    new.ends_at := new.starts_at + (old.ends_at - old.starts_at);
  end if;
  new.blocked_until := new.ends_at + make_interval(mins => service.buffer_minutes);
  return new;
end;
$$;

-- Free start times of a service on a day, by specialist: every 15 minutes
-- within the working hours, in the future, where the service and its pause
-- fit without touching another booking. Security invoker: a member sees the
-- slots of their own business; the bot calls it with the service role.
CREATE OR REPLACE FUNCTION "public"."free_slots"("p_business_id" "uuid", "p_product_id" bigint, "p_day" "date", "p_sales_id" bigint DEFAULT NULL::bigint) RETURNS TABLE("sales_id" bigint, "starts_at" timestamp with time zone)
    LANGUAGE "sql" STABLE
    SET "search_path" TO ''
    AS $$
    with service as (
        select p.duration_minutes, p.buffer_minutes
        from public.products p
        where p.id = p_product_id and p.business_id = p_business_id
          and p.kind = 'service' and p.duration_minutes is not null and not p.archived
    ),
    candidates as (
        select w.sales_id, slot
        from public.working_hours w
        cross join service s
        join public.businesses b on b.id = w.business_id
        cross join lateral generate_series(
            (p_day + w.starts_at) at time zone b.timezone,
            ((p_day + w.ends_at) at time zone b.timezone) - make_interval(mins => s.duration_minutes),
            interval '15 minutes'
        ) as slot
        where w.business_id = p_business_id
          and w.weekday = extract(isodow from p_day)
          and (p_sales_id is null or w.sales_id = p_sales_id)
    )
    select c.sales_id, c.slot
    from candidates c
    cross join service s
    where c.slot > now()
      and public.is_active_member(p_business_id, c.sales_id)
      and not exists (
          select 1 from public.bookings bk
          where bk.business_id = p_business_id
            and bk.sales_id = c.sales_id
            and bk.status <> 'cancelled'
            and tstzrange(bk.starts_at, bk.blocked_until)
                && tstzrange(c.slot, c.slot + make_interval(mins => s.duration_minutes + s.buffer_minutes))
      )
    order by c.slot, c.sales_id
$$;

create or replace trigger check_working_hours
    before insert or update on public.working_hours
    for each row execute function public.check_working_hours();

create or replace trigger check_booking
    before insert or update of business_id, sales_id, product_id, starts_at, ends_at on public.bookings
    for each row execute function public.check_booking();

-- Products with their stock, average cost and booking settings (the stock
-- part is declared in 14_products_stock.sql)
create or replace view public.products_summary with (security_invoker = on) as
select
    p.id,
    p.business_id,
    p.created_at,
    p.kind,
    p.name,
    p.sku,
    p.unit_code,
    p.price,
    p.currency,
    p.vat_rate_code,
    p.barcodes,
    p.description,
    p.archived,
    coalesce((
        select sum(case when m.to_warehouse_id is not null and m.from_warehouse_id is null then m.quantity
                        when m.from_warehouse_id is not null and m.to_warehouse_id is null then -m.quantity
                        else 0 end)
        from public.stock_moves m
        where m.product_id = p.id
    ), 0) as quantity,
    (
        select round(sum(m.quantity * m.unit_cost) / nullif(sum(m.quantity), 0))::bigint
        from public.stock_moves m
        where m.product_id = p.id
          and m.kind = 'receipt'
          and not exists (select 1 from public.stock_moves r where r.reverses_id = m.id)
    ) as average_cost,
    p.duration_minutes,
    p.buffer_minutes
from public.products p;

-- Active members of the current business who can take bookings, with the id
-- of their user profile (sales), which bookings and working hours refer to
create or replace view public.specialists with (security_invoker = on) as
select
    s.id,
    m.business_id,
    s.first_name,
    s.last_name,
    m.role
from public.members m
join public.sales s on s.user_id = m.user_id
where not m.disabled
  and m.business_id = public.current_business_id();

