-- Where a business stands: its plan, trial / active / read_only, until when,
-- what it may use. A business without a row is still being created: trial.
CREATE OR REPLACE FUNCTION "public"."subscription_of"("p_business_id" "uuid") RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  v_sub public.business_subscriptions;
  v_today date;
  v_plan public.plans;
  v_all text[] := array['messengers', 'automations', 'marketing', 'booking_page', 'weekly_report', 'costing', 'business_map', 'ai'];
begin
  select * into v_sub from public.business_subscriptions where business_id = p_business_id;
  select (now() at time zone b.timezone)::date into v_today from public.businesses b where b.id = p_business_id;
  select * into v_plan from public.plans where code = v_sub.plan_code;

  if v_sub.paid_until is not null and v_sub.paid_until >= v_today then
    return jsonb_build_object('plan', v_plan.code, 'status', 'active', 'ends_at', v_sub.paid_until,
      'features', to_jsonb(v_plan.features), 'max_members', v_plan.max_members);
  end if;
  if v_sub.business_id is null or v_sub.trial_ends_at > now() then
    return jsonb_build_object('plan', 'pro', 'status', 'trial', 'ends_at', coalesce(v_sub.trial_ends_at, now() + interval '30 days'),
      'features', to_jsonb(v_all), 'max_members', null);
  end if;
  return jsonb_build_object('plan', v_plan.code, 'status', 'read_only',
    'ends_at', coalesce(v_sub.paid_until::timestamptz, v_sub.trial_ends_at),
    'features', '[]'::jsonb, 'max_members', v_plan.max_members);
end;
$$;

CREATE OR REPLACE FUNCTION "public"."business_is_writable"("p_business_id" "uuid") RETURNS boolean
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$ select public.subscription_of(p_business_id)->>'status' <> 'read_only' $$;

CREATE OR REPLACE FUNCTION "public"."business_has_feature"("p_business_id" "uuid", "p_feature" "text") RETURNS boolean
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$ select coalesce(public.subscription_of(p_business_id)->'features' ? p_feature, false) $$;

-- People who count against the member limit: active members and pending
-- invitations
CREATE OR REPLACE FUNCTION "public"."counted_members"("p_business_id" "uuid") RETURNS integer
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
    select (select count(*) from public.members where business_id = p_business_id and not disabled)::integer
         + (select count(*) from public.user_invitations where business_id = p_business_id)::integer
$$;

-- What the app shows: the subscription of the current business and how many
-- people count against its member limit
CREATE OR REPLACE FUNCTION "public"."current_subscription"() RETURNS "jsonb"
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
    select public.subscription_of(public.current_business_id())
      || jsonb_build_object('members', public.counted_members(public.current_business_id()))
    where public.current_business_id() is not null
$$;

-- Stops writes of signed-in users in a read-only business, or into a table
-- of a feature its plan lacks (TG_ARGV[0]); removing such rows stays allowed
CREATE OR REPLACE FUNCTION "public"."guard_subscription"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  v_row jsonb := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  v_business uuid := (v_row->>'business_id')::uuid;
begin
  if coalesce(auth.role(), '') <> 'authenticated' or v_business is null then
    return case when tg_op = 'DELETE' then old else new end;
  end if;
  if not public.business_is_writable(v_business) then
    raise exception 'crm.subscription.errors.read_only' using errcode = 'P0001';
  end if;
  if tg_nargs > 0 and tg_op <> 'DELETE' and not public.business_has_feature(v_business, tg_argv[0]) then
    raise exception 'crm.subscription.errors.feature' using errcode = 'P0001', detail = tg_argv[0];
  end if;
  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

-- The member limit of the plan holds for everyone, the service role included
-- (invitations are accepted through it)
CREATE OR REPLACE FUNCTION "public"."guard_member_limit"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  v_new jsonb := to_jsonb(new);
  v_max integer;
  v_count integer;
begin
  if tg_table_name = 'members' then
    -- a disabled member does not count; an update that keeps a member active
    -- adds nobody
    if (v_new->>'disabled')::boolean then
      return new;
    end if;
    if tg_op = 'UPDATE' and not (to_jsonb(old)->>'disabled')::boolean then
      return new;
    end if;
  end if;
  v_max := (public.subscription_of(new.business_id)->>'max_members')::integer;
  if v_max is null then
    return new;
  end if;
  v_count := public.counted_members(new.business_id);
  -- an accepted invitation turns into a member: it is already counted
  if tg_table_name = 'members' then
    v_count := v_count - (select count(*) from public.user_invitations i
                          where i.business_id = new.business_id and i.user_id = new.user_id)::integer;
  end if;
  if v_count + 1 > v_max then
    raise exception 'crm.subscription.errors.member_limit' using errcode = 'P0001';
  end if;
  return new;
end;
$$;

-- Each business gets its subscription row (with its trial) when it is made
CREATE OR REPLACE FUNCTION "public"."create_business_subscription"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  insert into public.business_subscriptions (business_id) values (new.id) on conflict do nothing;
  return new;
end;
$$;

create or replace trigger create_business_subscription
    after insert on public.businesses
    for each row execute function public.create_business_subscription();

create or replace trigger guard_member_limit
    before insert or update of disabled on public.members
    for each row execute function public.guard_member_limit();
create or replace trigger guard_member_limit
    before insert on public.user_invitations
    for each row execute function public.guard_member_limit();

-- Read-only guard on every business table; feature tables name their feature
do $$
declare
  v_table text;
  v_feature text;
  v_features jsonb := '{
    "channels": "messengers", "conversations": "messengers", "messages": "messengers", "reply_templates": "messengers",
    "automations": "automations", "automation_sends": "automations",
    "marketing_accounts": "marketing", "posts": "marketing", "post_targets": "marketing",
    "booking_pages": "booking_page", "weekly_reports": "weekly_report",
    "cost_settings": "costing", "overhead_items": "costing", "product_cost_items": "costing", "product_price_rules": "costing"
  }';
begin
  for v_table in
    select c.table_name from information_schema.columns c
    join information_schema.tables t using (table_schema, table_name)
    where c.table_schema = 'public' and c.column_name = 'business_id' and t.table_type = 'BASE TABLE'
      and c.table_name not in ('business_subscriptions', 'subscription_events')
  loop
    v_feature := v_features->>v_table;
    execute format(
      'create or replace trigger "00_guard_subscription" before insert or update or delete on public.%I for each row execute function public.guard_subscription(%s)',
      v_table, coalesce(quote_literal(v_feature), ''));
  end loop;
end;
$$;

-- Platform admin: list businesses, turn a plan on until a date, edit prices
CREATE OR REPLACE FUNCTION "public"."is_platform_admin"() RETURNS boolean
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$ select exists (select 1 from public.platform_admins where user_id = (select auth.uid())) $$;

CREATE OR REPLACE FUNCTION "public"."platform_businesses"() RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if not public.is_platform_admin() then
    raise exception 'Only platform admins see all businesses' using errcode = '42501';
  end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
      'id', b.id, 'name', b.name, 'country_code', b.country_code, 'created_at', b.created_at,
      'owner_email', (select u.email from public.members m join auth.users u on u.id = m.user_id
                      where m.business_id = b.id and m.role = 'owner' order by m.created_at limit 1),
      'members', public.counted_members(b.id),
      'subscription', public.subscription_of(b.id)
    ) order by b.created_at desc)
    from public.businesses b where not b.is_demo), '[]'::jsonb);
end;
$$;

CREATE OR REPLACE FUNCTION "public"."set_business_subscription"("p_business_id" "uuid", "p_plan_code" "text", "p_paid_until" "date", "p_amount_minor" bigint DEFAULT 0, "p_note" "text" DEFAULT NULL::"text") RETURNS void
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  v_currency text;
begin
  if not public.is_platform_admin() then
    raise exception 'Only platform admins change plans' using errcode = '42501';
  end if;
  select currency into v_currency from public.plans where code = p_plan_code;
  if v_currency is null then
    raise exception 'Unknown plan %', p_plan_code using errcode = '22023';
  end if;
  if p_paid_until is null then
    raise exception 'The paid period needs an end date' using errcode = '22023';
  end if;
  if not exists (select 1 from public.businesses where id = p_business_id) then
    raise exception 'Unknown business' using errcode = '22023';
  end if;
  insert into public.business_subscriptions (business_id, plan_code, paid_until)
    values (p_business_id, p_plan_code, p_paid_until)
    on conflict (business_id) do update
      set plan_code = excluded.plan_code, paid_until = excluded.paid_until, updated_at = now();
  insert into public.subscription_events (business_id, plan_code, paid_until, amount_minor, currency, note, created_by)
    values (p_business_id, p_plan_code, p_paid_until, coalesce(p_amount_minor, 0), v_currency,
            nullif(trim(p_note), ''), auth.uid());
end;
$$;

CREATE OR REPLACE FUNCTION "public"."update_plan"("p_code" "text", "p_price_minor" bigint, "p_max_members" integer) RETURNS void
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if not public.is_platform_admin() then
    raise exception 'Only platform admins change plans' using errcode = '42501';
  end if;
  update public.plans set price_minor = p_price_minor, max_members = p_max_members where code = p_code;
  if not found then
    raise exception 'Unknown plan %', p_code using errcode = '22023';
  end if;
end;
$$;

-- Full copy of the current business for its owner: every business table,
-- without secrets (tokens, code hashes) and short-lived login rows
CREATE OR REPLACE FUNCTION "public"."export_business_data"() RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  v_business uuid := public.current_business_id();
  v_table text;
  v_rows jsonb;
  v_result jsonb;
begin
  if v_business is null or not public.is_admin() then
    raise exception 'Only the owner exports the data' using errcode = '42501';
  end if;
  select jsonb_build_object('business', jsonb_build_array(to_jsonb(b))) into v_result
    from public.businesses b where b.id = v_business;
  for v_table in
    select c.table_name from information_schema.columns c
    join information_schema.tables t using (table_schema, table_name)
    where c.table_schema = 'public' and c.column_name = 'business_id' and t.table_type = 'BASE TABLE'
      and c.table_name not in ('phone_codes', 'booking_sessions', 'staff_link_codes')
    order by c.table_name
  loop
    execute format(
      'select coalesce(jsonb_agg(to_jsonb(t) - %L::text[]), ''[]''::jsonb) from public.%I t where t.business_id = $1',
      array['access_token', 'token_expires_at', 'bot_token', 'webhook_secret', 'code_hash', 'token_hash'], v_table)
      into v_rows using v_business;
    v_result := v_result || jsonb_build_object(v_table, v_rows);
  end loop;
  return v_result;
end;
$$;

