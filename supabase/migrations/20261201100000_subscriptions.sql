-- Plans, subscriptions, read-only mode and full export (supabase/schemas/32_subscriptions.sql)

--
-- Plans and subscriptions
-- A business runs on one of three plans (start, business, pro). A new
-- business gets a 30-day trial with everything open. When the trial or the
-- paid period ends, the business turns read-only: its people still see and
-- export the data but add or change nothing until the plan is paid. Data is
-- never removed. Payment is manual for now: a platform admin turns a plan on
-- until a date; every change is kept in subscription_events (append-only).
--
-- Enforcement lives here, not in the UI: the guard_subscription trigger on
-- every business table stops writes of signed-in users when the business is
-- read-only, or when the table belongs to a feature its plan lacks (the
-- trigger argument). Service-role writes (bots, public booking page) pass, so
-- incoming client messages and bookings are never lost.
--

-- Prices and limits are data: the platform admin edits them
create table public.plans (
    code text primary key,
    sort smallint not null,
    price_minor bigint not null,
    currency text not null,
    -- null: no limit
    max_members integer,
    features text[] not null default '{}',
    constraint plans_code check (code in ('start', 'business', 'pro')),
    constraint plans_price check (price_minor >= 0),
    constraint plans_currency check (currency ~ '^[A-Z]{3}$'),
    constraint plans_max_members check (max_members is null or max_members > 0),
    constraint plans_features check (features <@ array['messengers', 'automations', 'marketing', 'booking_page', 'weekly_report', 'costing', 'business_map', 'ai'])
);

-- One row per business, made with the business
create table public.business_subscriptions (
    business_id uuid primary key references public.businesses(id) on delete cascade,
    plan_code text references public.plans(code),
    trial_ends_at timestamp with time zone not null default (now() + interval '30 days'),
    -- last paid day, inclusive, in the business time zone
    paid_until date,
    updated_at timestamp with time zone not null default now()
);

-- Every manual change of a plan: who, what, until when, how much was paid
create table public.subscription_events (
    id bigint generated by default as identity primary key,
    business_id uuid not null references public.businesses(id) on delete cascade,
    plan_code text not null references public.plans(code),
    paid_until date not null,
    amount_minor bigint not null default 0,
    currency text not null,
    note text,
    created_by uuid references auth.users(id) on delete set null,
    created_at timestamp with time zone not null default now(),
    constraint subscription_events_amount check (amount_minor >= 0),
    constraint subscription_events_currency check (currency ~ '^[A-Z]{3}$'),
    constraint subscription_events_note check (note is null or length(note) <= 500)
);
create index subscription_events_business_id_idx on public.subscription_events using btree (business_id);

-- People who run the platform itself (set by hand in the database)
create table public.platform_admins (
    user_id uuid primary key references auth.users(id) on delete cascade,
    created_at timestamp with time zone not null default now()
);

alter table public.plans enable row level security;
alter table public.business_subscriptions enable row level security;
alter table public.subscription_events enable row level security;
alter table public.platform_admins enable row level security;

create policy "Plans read" on public.plans for select to authenticated using (true);
create policy "Business read" on public.business_subscriptions for select to authenticated using (business_id = (select public.current_business_id()));
create policy "Owner read" on public.subscription_events for select to authenticated using (business_id = (select public.current_business_id()) and (select public.is_admin()));

revoke all on table public.plans from anon;
revoke all on table public.business_subscriptions from anon;
revoke all on table public.subscription_events from anon;
revoke all on table public.platform_admins from anon, authenticated;

