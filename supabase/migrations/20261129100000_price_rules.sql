    add column service_price_method text not null default 'margin',
    add column service_price_value numeric(12,2) not null default 30,
    add column goods_price_method text not null default 'markup',
    add column goods_price_value numeric(12,2) not null default 50,
    add column price_rounding text not null default 'none';

-- The margin a business already chose stays its rule for services
update public.cost_settings set service_price_value = target_margin_percent;

alter table public.cost_settings drop constraint cost_settings_target_margin;
alter table public.cost_settings drop column target_margin_percent;

alter table public.cost_settings
    add constraint cost_settings_service_price check (
        (service_price_method = 'margin' and service_price_value between 0 and 95)
        or (service_price_method = 'markup' and service_price_value between 0 and 1000)
        or (service_price_method = 'profit' and service_price_value >= 0)
    ),
    add constraint cost_settings_goods_price check (
        (goods_price_method = 'margin' and goods_price_value between 0 and 95)
        or (goods_price_method = 'markup' and goods_price_value between 0 and 1000)
        or (goods_price_method = 'profit' and goods_price_value >= 0)
    ),
    add constraint cost_settings_price_rounding check (price_rounding in ('none', '1', '10', '50', '100', '9', '99'));

CREATE OR REPLACE FUNCTION "public"."cost_inputs"() RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  biz_id uuid := public.current_business_id();
  settings public.cost_settings;
begin
  if biz_id is null or not public.can_read_costs() then
    raise exception 'Costs are for owners, managers and accountants' using errcode = '42501';
  end if;
  select * into settings from public.cost_settings s where s.business_id = biz_id;
  if not found then
    settings.business_id := biz_id;
    settings.load_percent := 75;
    settings.pay_mode := 'commission';
    settings.tax_percent := 0;
    settings.card_fee_percent := 0;
    settings.card_share_percent := 0;
    settings.service_price_method := 'margin';
    settings.service_price_value := 30;
    settings.goods_price_method := 'markup';
    settings.goods_price_value := 50;
    settings.price_rounding := 'none';
    settings.material_price := 'average';
  end if;

  return jsonb_build_object(
    'settings', to_jsonb(settings) - 'business_id' - 'updated_at',
    'overhead_monthly', (
        select coalesce(round(sum(case when o.kind = 'monthly' then o.amount else o.amount::numeric / o.months end)), 0)::bigint
        from public.overhead_items o where o.business_id = biz_id),
    -- A month is 52 weeks / 12
    'working_minutes_month', (
        select coalesce(round(sum(extract(epoch from (w.ends_at - w.starts_at)) / 60) * 52 / 12), 0)::bigint
        from public.working_hours w
        join public.sales s on s.id = w.sales_id
        join public.members m on m.user_id = s.user_id and m.business_id = w.business_id and not m.disabled
        where w.business_id = biz_id),
    'commission_percent', (
        select round(avg(m.commission_percent), 2)
        from public.members m
        where m.business_id = biz_id and not m.disabled and m.commission_percent is not null),
    'last_costs', (
        select coalesce(jsonb_object_agg(l.product_id::text, l.unit_cost), '{}'::jsonb)
        from (
            select distinct on (m.product_id) m.product_id, m.unit_cost
            from public.stock_moves m
            where m.business_id = biz_id and m.kind = 'receipt'
              and not exists (select 1 from public.stock_moves r where r.reverses_id = m.id)
            order by m.product_id, m.moved_at desc, m.id desc
        ) l),
    'income_taxes', (
        select coalesce(jsonb_agg(jsonb_build_object('code', t.code, 'rate', t.rate, 'label', t.label) order by t.rate desc), '[]'::jsonb)
        from public.tax_rates t
        join public.businesses b on b.country_code = t.country_code
        where b.id = biz_id and t.tax = 'income'
          and t.valid_from <= current_date and (t.valid_to is null or t.valid_to > current_date))
  );
end;
$$;

create table public.product_price_rules (
    id bigint generated by default as identity primary key,
    product_id bigint not null,
    business_id uuid not null default public.current_business_id(),
    updated_at timestamp with time zone not null default now(),
    -- Null: the rule of the business for its kind
    method text,
    -- Percent for margin and markup, minor units for profit
    value numeric(12,2),
    -- Null: the rounding of the business
    rounding text,
    constraint product_price_rules_rule check (
        (method is null and value is null)
        or (method = 'margin' and value is not null and value between 0 and 95)
        or (method = 'markup' and value is not null and value between 0 and 1000)
        or (method = 'profit' and value is not null and value >= 0)
    ),
    constraint product_price_rules_product_id_key unique (product_id),
    constraint product_price_rules_rounding check (rounding in ('none', '1', '10', '50', '100', '9', '99'))
);

alter table public.product_price_rules
    add constraint product_price_rules_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;
alter table public.product_price_rules
    add constraint product_price_rules_product_id_fkey foreign key (product_id, business_id) references public.products(id, business_id) on delete cascade;

create index product_price_rules_business_id_idx on public.product_price_rules using btree (business_id);

-- Sets the calculated prices a person confirmed and marks those products as
-- priced from the calculation. p_items: [{"id": 12, "price": 45000}, ...]
-- Security invoker: row level security keeps it to the current business.
CREATE OR REPLACE FUNCTION "public"."apply_calculated_prices"("p_items" "jsonb") RETURNS integer
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  item jsonb;
  new_price bigint;
  changed integer := 0;
begin
  if not public.can_manage_prices() or not public.can_manage_costs() then
    raise exception 'Only owners and managers set prices' using errcode = '42501';
  end if;
  if jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items) > 500 then
    raise exception 'Expected up to 500 prices' using errcode = '22023';
  end if;
  for item in select * from jsonb_array_elements(p_items) loop
    new_price := (item->>'price')::bigint;
    if new_price is null or new_price <= 0 then
      raise exception 'A price must be above zero' using errcode = '22023';
    end if;
    update public.products p
    set price = new_price
    where p.id = (item->>'id')::bigint
      and p.business_id = public.current_business_id();
    if found then
      changed := changed + 1;
      insert into public.product_price_rules (product_id)
      values ((item->>'id')::bigint)
      on conflict (product_id) do nothing;
    end if;
  end loop;
  return changed;
end;
$$;

CREATE OR REPLACE FUNCTION "public"."touch_product_price_rules"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create or replace trigger touch_product_price_rules
    before update on public.product_price_rules
    for each row execute function public.touch_product_price_rules();

